/**
 * ============================================================================
 * 🧸 AUTO FOLDER SCANNER (sync-photos.js)
 * ============================================================================
 * Scans:
 *   - photos/ (root folder)
 *   - photos/hero/
 *   - photos/timeline/
 *   - photos/her-solo/
 *   - photos/together/
 *   - photos/goofy/
 *   - love-letter/
 *   - music/
 * Automatically populates folder-manifest.js so every photo, letter, and song
 * is immediately live on the love page without requiring any manual config!
 * ============================================================================
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.dirname(__filename);

const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif', '.svg']);
const AUDIO_EXTS = new Set(['.mp3', '.wav', '.ogg', '.m4a', '.aac']);
const TEXT_EXTS = new Set(['.txt', '.md']);

function listFiles(relDir, allowedExts) {
  const fullDir = path.join(ROOT, relDir);
  if (!fs.existsSync(fullDir)) return [];
  return fs
    .readdirSync(fullDir)
    .filter((f) => {
      if (f.startsWith('.')) return false;
      const fullPath = path.join(fullDir, f);
      try {
        if (fs.statSync(fullPath).isDirectory()) return false;
      } catch (e) {
        return false;
      }
      return allowedExts.has(path.extname(f).toLowerCase());
    })
    .sort()
    .map((f) => `${relDir}/${f}`);
}

export function scanAll() {
  const rootPhotos = listFiles('photos', IMAGE_EXTS);
  const heroPhotos = listFiles('photos/hero', IMAGE_EXTS);
  const timelinePhotos = listFiles('photos/timeline', IMAGE_EXTS);
  const herSoloPhotos = listFiles('photos/her-solo', IMAGE_EXTS);
  const togetherPhotos = listFiles('photos/together', IMAGE_EXTS);
  const goofyPhotos = listFiles('photos/goofy', IMAGE_EXTS);

  // If root `photos/` has images, gracefully distribute any remaining ones to categories
  // so the user's photos show up everywhere across Hero, Timeline, and Gallery!
  const allRawPhotos = Array.from(new Set([
    ...rootPhotos,
    ...heroPhotos,
    ...timelinePhotos,
    ...herSoloPhotos,
    ...togetherPhotos,
    ...goofyPhotos
  ]));

  const manifest = {
    updatedAt: new Date().toISOString(),
    allPhotos: allRawPhotos,
    photos: {
      all: allRawPhotos,
      hero: heroPhotos.length > 0 ? heroPhotos : rootPhotos.slice(0, 3),
      timeline: timelinePhotos.length > 0 ? timelinePhotos : rootPhotos.slice(3, 8),
      'her-solo': herSoloPhotos.length > 0 ? herSoloPhotos : rootPhotos.slice(0, 6),
      together: togetherPhotos.length > 0 ? togetherPhotos : rootPhotos.slice(6, 11),
      goofy: goofyPhotos.length > 0 ? goofyPhotos : rootPhotos.slice(11)
    },
    music: listFiles('music', AUDIO_EXTS),
    loveLetterImages: listFiles('love-letter', IMAGE_EXTS),
    loveLetterText: null,
    loveLetterFile: null
  };

  const letterTexts = listFiles('love-letter', TEXT_EXTS);
  if (letterTexts.length > 0) {
    const chosen =
      letterTexts.find((f) => !f.endsWith('my-letter-to-latu.txt')) || letterTexts[0];
    manifest.loveLetterFile = chosen;
    try {
      manifest.loveLetterText = fs.readFileSync(path.join(ROOT, chosen), 'utf8');
    } catch (e) {
      console.warn('Could not read letter text:', e);
    }
  }

  const outContent = `// Auto-generated by sync-photos.js — Do not edit manually\nwindow.FOLDER_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
  fs.writeFileSync(path.join(ROOT, 'folder-manifest.js'), outContent, 'utf8');
  return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  const result = scanAll();
  console.log('💖 Synced folders into folder-manifest.js:', {
    allPhotosTotal: result.allPhotos.length,
    heroPhotos: result.photos.hero.length,
    timelinePhotos: result.photos.timeline.length,
    herSoloPhotos: result.photos['her-solo'].length,
    togetherPhotos: result.photos.together.length,
    goofyPhotos: result.photos.goofy.length,
    musicFiles: result.music.length,
    loveLetterFile: result.loveLetterFile,
    loveLetterImages: result.loveLetterImages.length
  });
}
